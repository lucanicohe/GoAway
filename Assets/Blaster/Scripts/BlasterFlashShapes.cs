using UnityEngine;

/// <summary>
/// The 3D muzzle flash shapes. Two flame silhouettes cut out of the green sprites, built as flat double sided meshes
/// (X = across, Z = forward, the white hot centre is at the origin). Because the mesh itself has the flame outline,
/// a thermal / opaque material still shows a clean flame shape instead of a whole square plane.
/// Built in code so there is nothing to break when the package is imported. UVs point into BlasterMuzzleFlashAtlas.png.
/// </summary>
public static class BlasterFlashShapes
{
    public const int Count = 2;

    private static readonly Mesh[] cache = new Mesh[Count];

    public static Mesh Get(int index)
    {
        index = Mathf.Abs(index) % Count;
        if (cache[index] == null)
            cache[index] = Build(index);
        return cache[index];
    }

    private static Mesh Build(int index)
    {
        float[] p = index == 0 ? PosA : PosB;     // X, Z pairs
        float[] t = index == 0 ? UvA : UvB;       // U, V pairs
        int[] tri = index == 0 ? TriA : TriB;     // oriented so the front face looks along +Y
        int n = p.Length / 2;

        Vector3[] v = new Vector3[n * 2];
        Vector3[] nrm = new Vector3[n * 2];
        Vector2[] uv = new Vector2[n * 2];
        for (int i = 0; i < n; i++)
        {
            v[i] = new Vector3(p[i * 2], 0f, p[i * 2 + 1]);
            v[n + i] = v[i];
            nrm[i] = Vector3.up;
            nrm[n + i] = Vector3.down;
            uv[i] = new Vector2(t[i * 2], t[i * 2 + 1]);
            uv[n + i] = uv[i];
        }

        int[] idx = new int[tri.Length * 2];
        for (int i = 0; i < tri.Length; i += 3)
        {
            idx[i] = tri[i];
            idx[i + 1] = tri[i + 1];
            idx[i + 2] = tri[i + 2];
            // back face: same triangle, reversed winding, second set of vertices
            idx[tri.Length + i] = n + tri[i];
            idx[tri.Length + i + 1] = n + tri[i + 2];
            idx[tri.Length + i + 2] = n + tri[i + 1];
        }

        Mesh m = new Mesh();
        m.name = index == 0 ? "BlasterFlashShapeA" : "BlasterFlashShapeB";
        m.vertices = v;
        m.normals = nrm;
        m.uv = uv;
        m.triangles = idx;
        m.RecalculateBounds();
        return m;
    }

